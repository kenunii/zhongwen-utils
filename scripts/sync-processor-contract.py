#!/usr/bin/env python3
"""Generate the tablet's embedded annotation contract from the shared source."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'pdf-import/src'))
from duchinese_pdf.line_contract import PROMPT, LINE_SCHEMA
from duchinese_pdf.annotation_schema import CONFUSABLE_GROUPS
from duchinese_pdf.policy import POLICY


def generated():
    prompt = PROMPT + '\nJSON schema:\n' + json.dumps(LINE_SCHEMA, ensure_ascii=False)
    groups = ', '.join(json.dumps(group, ensure_ascii=False) for group in CONFUSABLE_GROUPS)
    policy = ('// Code generated by scripts/sync-processor-contract.py; DO NOT EDIT.\npackage main\n\n'
              + 'var confusables = []string{' + groups + '}\n\n'
              + f"const defaultParallelPages = {POLICY['default_parallel_pages']}\n"
              + f"const maxParallelPages = {POLICY['max_parallel_pages']}\n"
              + f"const maxPreparedPageBytes = {POLICY['max_batch_bytes']}\n")
    return {ROOT/'processor/prompt.txt':prompt, ROOT/'processor/policy_generated.go':policy}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in generated().items():
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            if args.check: stale.append(str(path.relative_to(ROOT)))
            else: path.write_text(content,encoding='utf-8')
    if stale: parser.exit(1, 'Generated processor contract is stale: '+', '.join(stale)+'\n')


if __name__ == '__main__': main()
